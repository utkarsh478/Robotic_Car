#!/usr/bin/env bash
# Phase 0: record machine facts, check required packages, test headless Gazebo.
# Writes docs/ENVIRONMENT.md. Needs no sudo and changes nothing outside ~/ros2_ws.
# Usage:  cd ~/ros2_ws && bash tools/p0_env_check.sh
set -u
WS="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$WS/docs/ENVIRONMENT.md"
mkdir -p "$WS/docs"

# Source ROS if the shell hasn't.
if [ -z "${ROS_DISTRO:-}" ]; then
  for d in jazzy lyrical humble kilted rolling; do
    [ -f "/opt/ros/$d/setup.bash" ] && { set +u; source "/opt/ros/$d/setup.bash"; set -u; break; }
  done
fi
DISTRO="${ROS_DISTRO:-none}"
OS_VER="$(lsb_release -rs 2>/dev/null || echo unknown)"

{
echo "# ENVIRONMENT"
echo "_Generated by tools/p0_env_check.sh on $(date -Iseconds)_"
echo
echo "## Machine"
echo '```'
lsb_release -ds 2>/dev/null
echo "kernel: $(uname -r)"
echo "ROS_DISTRO: $DISTRO"
echo "/opt/ros: $(ls /opt/ros 2>/dev/null | tr '\n' ' ')"
echo "gz: $(gz sim --versions 2>/dev/null | tr '\n' ' ')"
echo "ign: $(ign gazebo --versions 2>/dev/null | tr '\n' ' ')"
echo "cpus: $(nproc)"
free -h | head -2
lspci 2>/dev/null | grep -iE "vga|3d" || true
command -v nvidia-smi >/dev/null && nvidia-smi --query-gpu=name,driver_version,memory.total --format=csv,noheader
command -v glxinfo >/dev/null && glxinfo -B 2>/dev/null | grep -E "OpenGL renderer|OpenGL version"
echo "bashrc ROS lines:"; grep -n "ros\|ROS" ~/.bashrc 2>/dev/null | grep -v "^\s*#" || echo "  (none)"
echo '```'
} > "$OUT"

# ---------- stack decision (SPEC §1) ----------
case "$OS_VER/$DISTRO" in
  24.04/jazzy)   DECISION="OK: Ubuntu 24.04 + Jazzy + Gazebo Harmonic (primary target)";;
  26.04/lyrical) DECISION="OK: Ubuntu 26.04 + Lyrical + Gazebo Jetty (check SPEC plugin/param names)";;
  24.04/none)    DECISION="NEEDS INSTALL: Ubuntu 24.04 without ROS -> install ROS 2 Jazzy";;
  26.04/none)    DECISION="NEEDS INSTALL: Ubuntu 26.04 without ROS -> install ROS 2 Lyrical";;
  22.04/humble)  DECISION="OK (adapted): Ubuntu 22.04 + Humble + Gazebo Fortress (ign CLI); supported to May 2027";;
  *)             DECISION="STOP: unsupported combination ($OS_VER/$DISTRO) -> ask before continuing";;
esac
printf "\n## Stack decision\n%s\n" "$DECISION" >> "$OUT"

# ---------- required packages (SPEC §1) ----------
MISSING=()
if [ "$DISTRO" != "none" ]; then
  PKGS="ros_gz_sim ros_gz_bridge gz_ros2_control gz_ros2_control_demos controller_manager
        diff_drive_controller joint_trajectory_controller joint_state_broadcaster xacro
        joint_state_publisher_gui robot_state_publisher nav2_bringup slam_toolbox robot_localization
        moveit_ros_move_group moveit_configs_utils cv_bridge tf2_tools teleop_twist_keyboard rviz2"
  printf "\n## ROS packages\n" >> "$OUT"
  for p in $PKGS; do
    if ros2 pkg prefix "$p" >/dev/null 2>&1; then echo "- [x] $p" >> "$OUT"
    else echo "- [ ] $p  MISSING" >> "$OUT"; MISSING+=("$p"); fi
  done
  for t in colcon rosdep check_urdf; do
    command -v "$t" >/dev/null || { echo "- [ ] tool $t MISSING" >> "$OUT"; MISSING+=("$t"); }
  done
  python3 -c "import cv2, numpy" 2>/dev/null || { echo "- [ ] python3 opencv/numpy MISSING" >> "$OUT"; MISSING+=("python3-opencv"); }
fi

if [ ${#MISSING[@]} -gt 0 ]; then
  D="$DISTRO"
  APT="sudo apt install -y ros-$D-desktop ros-$D-ros-gz ros-$D-gz-ros2-control ros-$D-gz-ros2-control-demos \
ros-$D-ros2-control ros-$D-ros2-controllers ros-$D-xacro ros-$D-joint-state-publisher-gui \
ros-$D-navigation2 ros-$D-nav2-bringup ros-$D-slam-toolbox ros-$D-robot-localization ros-$D-moveit \
ros-$D-cv-bridge ros-$D-tf2-tools ros-$D-teleop-twist-keyboard \
python3-colcon-common-extensions python3-rosdep python3-opencv python3-numpy liburdfdom-tools"
  printf "\n## Missing — run this, then rerun the script\n\`\`\`\n%s\n\`\`\`\n" "$APT" >> "$OUT"
fi

# ---------- headless Gazebo RTF ----------
RTF="not run"
GZ=""; command -v gz >/dev/null && gz sim --versions >/dev/null 2>&1 && GZ="gz sim"; GZT="gz topic"
[ -z "$GZ" ] && command -v ign >/dev/null && { GZ="ign gazebo"; GZT="ign topic"; }
if [ "$DISTRO" != "none" ] && [ -n "$GZ" ]; then
  setsid $GZ -s -r --headless-rendering shapes.sdf > /tmp/p0_gz.log 2>&1 &
  GZPID=$!
  sleep 10
  RTF="$(timeout 8 $GZT -e -t /stats -n 1 2>/dev/null | grep -m1 real_time_factor | awk '{print $2}')"
  kill -- -"$GZPID" 2>/dev/null; sleep 1; kill -9 -- -"$GZPID" 2>/dev/null
  [ -z "$RTF" ] && RTF="no /stats received (see /tmp/p0_gz.log)"
fi
printf "\n## Headless Gazebo\nshapes.sdf real_time_factor: %s (gate: >= 0.9)\n" "$RTF" >> "$OUT"

cat "$OUT"
echo
echo "=== P0 SUMMARY ==="
echo "Stack:   $DECISION"
echo "Missing: ${#MISSING[@]} ${MISSING[*]:-}"
echo "RTF:     $RTF"
